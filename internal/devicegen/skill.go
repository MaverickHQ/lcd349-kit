// The skill (plugin/skills/lcd349): references rendered from device.json,
// the public headers and examples/gallery, and the generated block in
// SKILL.md. Board facts reach the skill only this way (requirement 8.3).
const (
	skillDir     = "plugin/skills/lcd349"
	headerDir    = "components/lcd349/include"
	galleryDir   = "examples/gallery/main"
	blockBegin   = "<!-- BEGIN GENERATED by internal/devicegen from device/device.json; edit the template, not this block -->"
	blockEnd     = "<!-- END GENERATED -->"
	generatedTag = "<!-- Code generated by internal/devicegen. DO NOT EDIT. -->"
)

// skillOutputs are rendered from templates with the view and recipe sources.
var skillOutputs = []struct{ path, tmpl string }{
	{skillDir + "/references/design-guide.md", "design_guide_md.tmpl"},
	{skillDir + "/references/hardware-checklist.md", "hardware_checklist_md.tmpl"},
	{skillDir + "/references/recipes.md", "recipes_md.tmpl"},
}

// Public headers in the order the API reference presents them.
var headerOrder = []string{"lcd349.h", "lcd349_core.h", "lcd349_display.h", "lcd349_input.h", "lcd349_power.h",
	"lcd349_audio.h", "lcd349_rtc.h", "lcd349_kv.h", "lcd349_wifi.h", "lcd349_console.h", "lcd349_board.h"}

// RenderSkill renders the skill's generated files from the repository at root.
// generated holds the files Render produced in this run: the API reference
// reads the generated header from it, not the copy on disk, so one run is
// enough after device.json changes.
func RenderSkill(root string, d *Device, raw []byte, generated map[string][]byte) (map[string][]byte, error) {
	v, err := buildView(d, raw)
	if err != nil {
		return nil, err
	}
	recipes, err := recipeRegions(filepath.Join(root, galleryDir))
	if err != nil {
		return nil, err
	}
	used := map[string]bool{}
	fm := template.FuncMap{
		"recipe": func(name string) (string, error) {
			code, ok := recipes[name]
			if !ok {
				return "", fmt.Errorf("no /* recipe:start %s */ region in %s", name, galleryDir)
			}
			used[name] = true
			return code, nil
		},
		// mm converts landscape pixels to millimetres on the panel.
		"mm": func(px float64) string {
			return strconv.FormatFloat(math.Round(px/d.Display.PxPerMM*10)/10, 'f', -1, 64)
		},
		"pxf": func(i int) float64 { return float64(i) },
		"div": func(a, b int) int { return a / b },
		"sub": func(a, b int) int { return a - b },
		"mod": func(a, b int) int { return a % b },
	}
	for k, f := range funcs {
		fm[k] = f
	}
	t, err := template.New("").Funcs(fm).ParseFS(templateFS, "templates/skill/*.tmpl")
	if err != nil {
		return nil, err
	}
	out := map[string][]byte{}
	for _, o := range skillOutputs {
		var buf bytes.Buffer
		if err := t.ExecuteTemplate(&buf, o.tmpl, v); err != nil {
			return nil, fmt.Errorf("%s: %w", o.path, err)
		}
		out[o.path] = buf.Bytes()
	}
	var unused []string
	for name := range recipes {
		if !used[name] {
			unused = append(unused, name)
		}
	}
	if len(unused) > 0 {
		sort.Strings(unused)
		return nil, fmt.Errorf("recipes.md doesn't show the gallery regions %s", strings.Join(unused, ", "))
	}

	api, err := apiReference(root, generated)
	if err != nil {
		return nil, err
	}
	out[skillDir+"/references/sdk-api.md"] = api

	var block bytes.Buffer
	if err := t.ExecuteTemplate(&block, "skill_block.tmpl", v); err != nil {
		return nil, fmt.Errorf("SKILL.md block: %w", err)
	}
	skill, err := os.ReadFile(filepath.Join(root, skillDir, "SKILL.md"))
	if err != nil {
		return nil, err
	}
	if out[skillDir+"/SKILL.md"], err = replaceBlock(skill, block.Bytes()); err != nil {
		return nil, fmt.Errorf("SKILL.md: %w", err)
	}

	// The docs: the same API reference, and the README's fidelity list.
	out["docs/sdk-api.md"] = api
	var readmeBlock bytes.Buffer
	if err := t.ExecuteTemplate(&readmeBlock, "readme_block.tmpl", v); err != nil {
		return nil, fmt.Errorf("README.md block: %w", err)
	}
	readme, err := os.ReadFile(filepath.Join(root, "README.md"))
	if err != nil {
		return nil, err
	}
	if out["README.md"], err = replaceBlock(readme, readmeBlock.Bytes()); err != nil {
		return nil, fmt.Errorf("README.md: %w", err)
	}
	return out, nil
}

// replaceBlock puts content between SKILL.md's generated-block markers.
func replaceBlock(doc, content []byte) ([]byte, error) {
	b := bytes.Index(doc, []byte(blockBegin))
	e := bytes.Index(doc, []byte(blockEnd))
	if b < 0 || e < b {
		return nil, fmt.Errorf("no generated block (%q ... %q)", blockBegin, blockEnd)
	}
	var out bytes.Buffer
	out.Write(doc[:b+len(blockBegin)])
	out.WriteString("\n")
	out.Write(bytes.TrimSpace(content))
	out.WriteString("\n")
	out.Write(doc[e:])
	return out.Bytes(), nil
}

var regionRe = regexp.MustCompile(`(?s)/\* recipe:start ([a-z0-9-]+) \*/\n(.*?)/\* recipe:end \*/`)

// recipeRegions collects the code between /* recipe:start NAME */ and
// /* recipe:end */ in the gallery's sources. A name may span files (a
// header, then its source): the parts are joined, headers first.
func recipeRegions(dir string) (map[string]string, error) {
	files, err := filepath.Glob(filepath.Join(dir, "*.[ch]"))
	if err != nil {
		return nil, err
	}
	sort.Slice(files, func(i, j int) bool {
		hi, hj := strings.HasSuffix(files[i], ".h"), strings.HasSuffix(files[j], ".h")
		if hi != hj {
			return hi
		}
		return files[i] < files[j]
	})
	out := map[string]string{}
	for _, f := range files {
		b, err := os.ReadFile(f)
		if err != nil {
			return nil, err
		}
		for _, m := range regionRe.FindAllSubmatch(b, -1) {
			name, code := string(m[1]), strings.TrimRight(string(m[2]), "\n")
			if prev, ok := out[name]; ok {
				code = prev + "\n\n" + code
			}
			out[name] = code
		}
	}
	if len(out) == 0 {
		return nil, fmt.Errorf("no recipe regions in %s", dir)
	}
	return out, nil
}

// apiReference renders the public headers as one reference: each header's
// leading comment as prose, then its declarations with their comments.
// Headers in generated are taken from there rather than from disk.
func apiReference(root string, generated map[string][]byte) ([]byte, error) {
	dir := filepath.Join(root, headerDir)
	var b bytes.Buffer
	b.WriteString(generatedTag + "\n")
	b.WriteString("# The lcd349 C API\n\n")
	b.WriteString("Generated from the public headers in `components/lcd349/include`, so it matches the code. ")
	b.WriteString("Include `lcd349.h` only. Use LVGL 9 for the UI and these calls for everything physical; then a product builds unchanged for the board and the emulator.\n")
	seen := map[string]bool{}
	for _, name := range headerOrder {
		src, ok := generated[headerDir+"/"+name]
		if !ok {
			var err error
			if src, err = os.ReadFile(filepath.Join(dir, name)); err != nil {
				return nil, err
			}
		}
		seen[name] = true
		intro, body := splitHeader(string(src))
		fmt.Fprintf(&b, "\n## `%s`\n\n", name)
		if intro != "" {
			b.WriteString(intro + "\n")
		}
		if body != "" {
			b.WriteString("\n```c\n" + body + "\n```\n")
		}
	}
	all, _ := filepath.Glob(filepath.Join(dir, "*.h"))
	for _, h := range all {
		if !seen[filepath.Base(h)] {
			return nil, fmt.Errorf("%s isn't in the API reference's header order (internal/devicegen/skill.go)", filepath.Base(h))
		}
	}
	return b.Bytes(), nil
}

var (
	dropLine = regexp.MustCompile(`^\s*(#pragma once|#include .*|#ifdef __cplusplus|#endif|extern "C" \{|\})\s*$`)
	blankRun = regexp.MustCompile(`\n{3,}`)
)

// splitHeader separates a header's leading comment (as prose) from the rest.
func splitHeader(src string) (string, string) {
	intro := ""
	if strings.HasPrefix(src, "/*") {
		end := strings.Index(src, "*/")
		var lines []string
		for _, l := range strings.Split(src[2:end], "\n") {
			l = strings.TrimPrefix(strings.TrimSpace(l), "*")
			l = strings.TrimPrefix(l, " ")
			if strings.HasPrefix(l, "SPDX-License-Identifier") {
				continue
			}
			lines = append(lines, l)
		}
		intro = strings.TrimSpace(strings.Join(lines, "\n"))
		src = src[end+2:]
	}
	var keep []string
	for _, l := range strings.Split(src, "\n") {
		if !dropLine.MatchString(l) {
			keep = append(keep, strings.TrimRight(l, " "))
		}
	}
	body := strings.TrimSpace(blankRun.ReplaceAllString(strings.Join(keep, "\n"), "\n\n"))
	return intro, body
}
