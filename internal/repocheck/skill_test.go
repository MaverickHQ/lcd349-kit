package repocheck

import (
	"os"
	"path/filepath"
	"regexp"
	"strings"
	"testing"

	"go.yaml.in/yaml/v3"
)

const skillDir = "../../plugin/skills/lcd349"

func readSkill(t *testing.T) (front map[string]any, body string) {
	t.Helper()
	b, err := os.ReadFile(filepath.Join(skillDir, "SKILL.md"))
	if err != nil {
		t.Fatal(err)
	}
	s := string(b)
	if !strings.HasPrefix(s, "---\n") {
		t.Fatal("SKILL.md has no frontmatter")
	}
	end := strings.Index(s[4:], "\n---\n")
	if end < 0 {
		t.Fatal("SKILL.md's frontmatter isn't closed")
	}
	if err := yaml.Unmarshal([]byte(s[4:4+end]), &front); err != nil {
		t.Fatalf("frontmatter: %v", err)
	}
	return front, s
}

// TestSkillSize enforces KN8: SKILL.md under 500 lines, and description plus
// when_to_use within the 1,536 characters Claude Code keeps.
func TestSkillSize(t *testing.T) {
	front, body := readSkill(t)
	if n := strings.Count(body, "\n"); n > 500 {
		t.Errorf("SKILL.md is %d lines; KN8 allows 500: move detail into references/", n)
	}
	desc, _ := front["description"].(string)
	when, _ := front["when_to_use"].(string)
	if front["name"] != "lcd349" || desc == "" || when == "" {
		t.Fatalf("frontmatter needs name lcd349, description and when_to_use: %v", front)
	}
	if n := len([]rune(desc)) + len([]rune(when)); n > 1536 {
		t.Errorf("description + when_to_use is %d characters; KN8 allows 1,536", n)
	}
}

// TestSkillReferencesLinked: every reference file is pointed to from
// SKILL.md, and every pointer names a file that exists.
func TestSkillReferencesLinked(t *testing.T) {
	_, body := readSkill(t)
	files, _ := filepath.Glob(filepath.Join(skillDir, "references", "*.md"))
	if len(files) < 8 {
		t.Fatalf("only %d reference files", len(files))
	}
	for _, f := range files {
		if !strings.Contains(body, "references/"+filepath.Base(f)) {
			t.Errorf("SKILL.md doesn't point to references/%s", filepath.Base(f))
		}
	}
	for _, m := range regexp.MustCompile(`references/([a-z-]+\.md)`).FindAllStringSubmatch(body, -1) {
		if _, err := os.Stat(filepath.Join(skillDir, "references", m[1])); err != nil {
			t.Errorf("SKILL.md points to references/%s, which doesn't exist", m[1])
		}
	}
}

// TestSkillHasNoHandCopiedFacts enforces requirement 8.3: board facts and
// thresholds reach the skill only through internal/devicegen. Hand-written
// text (SKILL.md outside its generated block, and the references that
// aren't generated) carries no pixel, millimetre or ppi values, and not the
// screen's dimensions.
func TestSkillHasNoHandCopiedFacts(t *testing.T) {
	_, body := readSkill(t)
	b := strings.Index(body, "<!-- BEGIN GENERATED")
	e := strings.Index(body, "<!-- END GENERATED -->")
	if b < 0 || e < b {
		t.Fatal("SKILL.md has no generated block")
	}
	texts := map[string]string{"SKILL.md (outside the generated block)": body[:b] + body[e:]}
	files, _ := filepath.Glob(filepath.Join(skillDir, "references", "*.md"))
	for _, f := range files {
		c, _ := os.ReadFile(f)
		if !strings.Contains(string(c), "Code generated by internal/devicegen") {
			texts["references/"+filepath.Base(f)] = string(c)
		}
	}
	if len(texts) < 3 {
		t.Fatalf("expected SKILL.md and at least two hand-written references, got %d texts", len(texts))
	}
	fact := regexp.MustCompile(`\b\d+(\.\d+)?\s?(px|mm|ppi)\b|\b(640|172)\b`)
	for name, text := range texts {
		for i, line := range strings.Split(text, "\n") {
			if m := fact.FindString(line); m != "" {
				t.Errorf("%s:%d has %q: put board facts in device.json and the generated text, not by hand", name, i+1, m)
			}
		}
	}
}
